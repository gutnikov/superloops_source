#!/usr/bin/env python3
"""The catalog of loops (../loops) and the super-loops (../super-loops): build the index and validate both.

    python3 catalog.py index   write loops/index.yaml and the list of loops in loops/README.md from the cards
    python3 catalog.py check   validate every card, the template, every super-loop and the links of the documents,
                               and fail if index.yaml or the README's list is out of date

A loop's card is loops/<id>/card.md; loops/loop.schema.json defines its frontmatter, loops/FORMAT.md the rest.
Needs PyYAML. index.yaml holds only scalars and flow lists; strings are written as JSON, which is valid YAML, so that
scripts/loops.py can read it without PyYAML.
"""
import collections
import json
import pathlib
import re
import sys

HARNESS = pathlib.Path(__file__).resolve().parent.parent
LOOPS = HARNESS / "loops"
SCHEMA = LOOPS / "loop.schema.json"
TEMPLATE = LOOPS / "_template" / "card.md"
INDEX = LOOPS / "index.yaml"
README = LOOPS / "README.md"
SUPER = HARNESS / "super-loops"
HUMAN = LOOPS / "human-in-the-loop.md"

PHASES = ["entry", "oracle", "work", "gate", "release", "confirmation"]
SUPER_SECTIONS = ("## Super-loop", "## Oracle", "## Phases", "## Gate", "## Confirmation", "## Exits", "## Trace",
                  "## When a project needs it", "## Sources")
SECTIONS = ["Why", "How it works", "Set up", "Notes", "Agent step"]  # in this order
REQUIRED_SECTIONS = ["Why", "How it works", "Set up"]
SPEEDS = ["sub-second", "seconds", "minutes", "hours", "days", "weeks"]
INDEX_FIELDS = ["summary", "sensor", "ilities", "places", "stages", "speed", "needs", "agent", "related", "when",
                "initiator", "sync", "assesses"]
IMAGE_MAX_BYTES = 300 * 1024
FENCE = re.compile(r"^```.*?^```[^\n]*$", re.S | re.M)
LIST_BEGIN, LIST_END = "<!-- loops:begin: generated by scripts/catalog.py index -->", "<!-- loops:end -->"
CARD_LINK = r"\]\(\.\./loops/([a-z0-9-]+)/card\.md\)"
# A card tells the harness engineer and the agent what to do. A sentence about what its source says or leaves out
# is research notes, not an instruction (FORMAT.md, "The voice").
SOURCE_TALK = [
    re.compile(r"\b(?:the|one of the|the card's)\s+(?:sources?|research|note|source note|source entry)\b"
               r"(?!\s+(?:code|file|files|tree|map|branch|repository|of truth|control))", re.I),
    re.compile(r"\b(?:cites|gives|has|names)\s+no\s+(?:primary\s+|outside\s+)?sources?\b", re.I),
    re.compile(r"\bsettles?\s+what\b|\bleaves?\s+(?:open|out)\b", re.I),
]


def yaml():
    try:
        import yaml as module
    except ImportError:
        sys.exit("catalog.py needs PyYAML: python3 -m pip install pyyaml")
    return module


def read(path):
    """(frontmatter as a dict or None, body, problem or None) of a Markdown file."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return None, text, None
    try:
        return yaml().safe_load(m.group(1)), text[m.end():], None
    except yaml().YAMLError as e:
        return None, text[m.end():], "the frontmatter is not valid YAML: %s" % str(e).splitlines()[0]


def schema():
    return json.loads(SCHEMA.read_text(encoding="utf-8"))


def loop_cards():
    """loops/<id>/card.md; the template is not a card."""
    return sorted(p for p in LOOPS.glob("*/card.md") if not p.parent.name.startswith("_"))


def loops():
    """[frontmatter] of every card that has one, by id."""
    out = []
    for path in loop_cards():
        fm, _, _ = read(path)
        if isinstance(fm, dict):
            out.append(fm)
    return out


# ---------------------------------------------------------------- the index and the README's list

def ility_titles():
    """[(ility, description)] in the schema's order."""
    return [(o["const"], o["description"]) for o in schema()["$defs"]["ility"]["oneOf"]]


def build_index():
    out = ["# Generated by scripts/catalog.py from loops/<id>/card.md.",
           "# Do not edit by hand: change the card, then run `python3 scripts/catalog.py index`.",
           "", "ilities:"]
    out += ["  %s: %s" % (i, json.dumps(d, ensure_ascii=False)) for i, d in ility_titles()]
    out += ["", "loops:"]
    for fm in loops():
        out.append("  - id: %s" % fm.get("id"))
        out.append("    title: %s" % json.dumps(fm.get("title"), ensure_ascii=False))
        out.append("    path: %s/card.md" % fm.get("id"))
        for key in INDEX_FIELDS:
            if key not in fm:
                continue
            v = fm[key]
            if isinstance(v, list):
                out.append("    %s: [%s]" % (key, ", ".join(str(x) for x in v)))
            elif key == "summary":
                out.append("    %s: %s" % (key, json.dumps(v, ensure_ascii=False)))
            else:
                out.append("    %s: %s" % (key, v))
    out += ["", "# The loops at each place: <super-loop>/<phase>, or harness:<super-loop>/<phase> at the harness level",
            "# (super-loops/). The Phases table of each super-loop names the same loops, except in the work phase.",
            "by_place:"]
    out += ["  %s: [%s]" % (place, ", ".join(ids)) for place, ids in places_index()]
    return "\n".join(out) + "\n"


def build_list():
    """The README's list of loops: by the main ility, the first in a card's ilities."""
    by = collections.defaultdict(list)
    for fm in loops():
        main = (fm.get("ilities") or ["?"])[0]
        by[main].append(fm)
    out = [LIST_BEGIN, ""]
    for ility, description in ility_titles():
        if not by.get(ility):
            continue
        out += ["### %s" % ility.capitalize(), "", "_%s_" % description, ""]
        out += ["- [%s](%s/card.md): %s" % (fm.get("title") or fm.get("id"), fm.get("id"), fm.get("summary", ""))
                for fm in sorted(by[ility], key=lambda f: str(f.get("title") or f.get("id")).lower())]
        out.append("")
    out.append(LIST_END)
    return "\n".join(out)


def readme_with_list(text):
    begin, end = text.find(LIST_BEGIN), text.find(LIST_END)
    if begin < 0 or end < begin:
        return None
    return text[:begin] + build_list() + text[end + len(LIST_END):]


# ---------------------------------------------------------------- places and the super-loops

def super_loop_phases():
    """{super-loop id: its phases}, from the cards in super-loops/, in the order super-loops/README.md links them."""
    phases = {}
    for path in sorted(SUPER.glob("*.md")):
        fm, _, _ = read(path)
        if isinstance(fm, dict) and fm.get("id"):
            phases[fm["id"]] = fm.get("phases") or []
    readme = (SUPER / "README.md").read_text(encoding="utf-8") if (SUPER / "README.md").exists() else ""
    order = [n for n in dict.fromkeys(re.findall(r"\]\(([a-z-]+)\.md\)", readme)) if n in phases]
    return {n: phases[n] for n in order + [n for n in phases if n not in order]}


def places_index():
    """[(place, [loop ids])]: the product level first, then by super-loop and phase."""
    by = collections.defaultdict(list)
    for fm in loops():
        for token in fm.get("places") or []:
            by[token].append(fm.get("id"))
    order = list(super_loop_phases())

    def key(token):
        level, _, place = token.rpartition(":")
        loop, _, phase = place.partition("/")
        return (level, order.index(loop) if loop in order else len(order),
                PHASES.index(phase) if phase in PHASES else len(PHASES), token)
    return [(t, sorted(by[t])) for t in sorted(by, key=key)]


def place_problem(token, loop_phases):
    """None when the token is <super-loop>/<phase> or harness:<super-loop>/<phase> and that super-loop has the phase."""
    level, _, place = token.rpartition(":")
    loop, _, phase = place.partition("/")
    if level not in ("", "harness"):
        return "has an unknown level %r; the only one is harness" % level
    if loop not in loop_phases:
        return "names no super-loop; they are %s" % ", ".join(loop_phases)
    if phase not in loop_phases[loop]:
        return "names a phase that %s has not; it has %s" % (loop, ", ".join(loop_phases[loop]))
    return None


def phase_rows(text):
    """{phase: {loop ids linked in its row}}, from the Phases table of a super-loop card."""
    m = re.search(r"^## Phases\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    rows = {}
    for line in (m.group(1) if m else "").splitlines():
        cells = line.split("|")
        if len(cells) > 2 and cells[1].strip() in PHASES:
            rows[cells[1].strip()] = set(re.findall(CARD_LINK, line))
    return rows


def check_places(places_of):
    """The Phases tables of the super-loops and the places in the cards say the same thing. Every loop in a row has
    that place, and every loop with a place is in its row, except in the work phase: that row names a few of the inner
    loops, and index.yaml lists all of them under by_place. The harness level's document links exactly the loops that
    have a harness: place."""
    errors = []
    for path in sorted(SUPER.glob("*.md")):
        fm, body, _ = read(path)
        if not isinstance(fm, dict):
            continue
        loop, rows = fm.get("id"), phase_rows(body)
        for phase, ids in sorted(rows.items()):
            for i in sorted(ids & set(places_of)):
                if "%s/%s" % (loop, phase) not in places_of[i]:
                    errors.append("super-loops/%s: %s is in the %s row, but its card has no place %s/%s"
                                  % (path.name, i, phase, loop, phase))
        for i, places in sorted(places_of.items()):
            for token in places:
                tloop, _, tphase = token.partition("/")
                if tloop == loop and tphase != "work" and i not in rows.get(tphase, set()):
                    errors.append("loops/%s/card.md: place %s, but the %s row of super-loops/%s does not name it"
                                  % (i, token, tphase, path.name))
    level = SUPER / "harness-level.md"
    linked = set(re.findall(CARD_LINK, level.read_text(encoding="utf-8"))) if level.exists() else set()
    for i, places in sorted(places_of.items()):
        harness = any(t.startswith("harness:") for t in places)
        if harness and i not in linked:
            errors.append("loops/%s/card.md: a harness: place, but super-loops/harness-level.md does not link it" % i)
        if i in linked and not harness:
            errors.append("super-loops/harness-level.md links %s, but its card has no harness: place" % i)
    return errors


def check_human_page(human):
    """loops/human-in-the-loop.md lists every loop where a person gives the signal, and no other."""
    if not HUMAN.exists():
        return ["loops/human-in-the-loop.md is missing"]
    linked = set(re.findall(r"\]\(([a-z0-9-]+)/card\.md\)", HUMAN.read_text(encoding="utf-8")))
    return (["loops/%s/card.md: sensor: human, but loops/human-in-the-loop.md does not link it" % i
             for i in sorted(human - linked)] +
            ["loops/human-in-the-loop.md links %s, but its card's sensor is not human" % i
             for i in sorted(linked - human)])


def check_super_loops():
    """The super-loop cards: id, title, phases from the vocabulary and in its order, sections, a link from the
    README. A file without frontmatter, such as the harness level, is a document about the super-loops, not a card."""
    errors = []
    readme = SUPER / "README.md"
    listed = readme.read_text(encoding="utf-8") if readme.exists() else ""
    for path in sorted(SUPER.glob("*.md")):
        if path.name == "README.md":
            continue
        rel = "super-loops/%s" % path.name
        if "](%s)" % path.name not in listed:
            errors.append("super-loops/README.md does not link %s" % path.name)
        fm, body, problem = read(path)
        if problem:
            errors.append("%s: %s" % (rel, problem))
        if not isinstance(fm, dict):
            continue
        if fm.get("id") != path.stem:
            errors.append("%s: id %r does not match the file name" % (rel, fm.get("id")))
        if "# %s\n" % fm.get("title") not in body:
            errors.append("%s: H1 does not match the title" % rel)
        phases = fm.get("phases") or []
        unknown = [p for p in phases if p not in PHASES]
        if unknown or not phases:
            errors.append("%s: phases %s: each must be one of %s" % (rel, phases, ", ".join(PHASES)))
        elif phases != [p for p in PHASES if p in phases]:
            errors.append("%s: phases are not in the order %s" % (rel, " → ".join(PHASES)))
        for key in ("entry", "exits"):
            if not fm.get(key):
                errors.append("%s: no %s" % (rel, key))
        for section in SUPER_SECTIONS:
            if section + "\n" not in body:
                errors.append("%s: missing %s" % (rel, section))
    return errors


# ---------------------------------------------------------------- the cards

URI = re.compile(r"^https?://[^\s/$.?#][^\s]*$")
TYPES = {"object": dict, "array": list, "string": str, "boolean": bool}


def schema_errors(value, schema, root, where=""):
    """The errors of a value against a JSON Schema, in the subset loop.schema.json uses (its $comment names it)."""
    at = where or "the frontmatter"
    if schema is True:
        return []
    if schema is False:
        return ["%s is not allowed" % at]
    if "$ref" in schema:
        errors = schema_errors(value, root["$defs"][schema["$ref"].rpartition("/")[2]], root, where)
        rest = {k: v for k, v in schema.items() if k not in ("$ref", "description")}
        return errors + (schema_errors(value, rest, root, where) if rest else [])
    expected = schema.get("type")
    if expected and not isinstance(value, TYPES[expected]):
        return ["%s is not %s %s" % (at, "an" if expected[0] in "aeiou" else "a", expected)]
    errors = []
    if "const" in schema and value != schema["const"]:
        errors.append("%s is not %s" % (at, schema["const"]))
    if "enum" in schema and value not in schema["enum"]:
        errors.append("%s: %r is not one of %s" % (at, value, ", ".join(schema["enum"])))
    if "oneOf" in schema:
        matched = sum(1 for s in schema["oneOf"] if not schema_errors(value, s, root, where))
        if matched != 1:
            consts = [s["const"] for s in schema["oneOf"] if "const" in s]
            if len(consts) == len(schema["oneOf"]):
                errors.append("%s: %r is not one of %s" % (at, value, ", ".join(consts)))
            else:
                errors.append("%s matches %d of its oneOf schemas, not one" % (at, matched))
    if "not" in schema and not schema_errors(value, schema["not"], root, where):
        errors.append("%s: %s" % (at, schema.get("description", "is not allowed")))
    if "if" in schema:
        branch = "else" if schema_errors(value, schema["if"], root, where) else "then"
        if branch in schema:
            errors += schema_errors(value, schema[branch], root, where)
    if isinstance(value, dict):
        props = schema.get("properties", {})
        errors += ["%s has no %s" % (at, key) for key in schema.get("required", []) if key not in value]
        for key, item in value.items():
            if key in props:
                errors += schema_errors(item, props[key], root, "%s.%s" % (where, key) if where else str(key))
            elif schema.get("additionalProperties") is False:
                errors.append("%sunknown field %s" % ("%s: " % where if where else "", key))
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append("%s is empty" % at if not value else "%s has fewer than %d items" % (at, schema["minItems"]))
        if len(value) > schema.get("maxItems", len(value)):
            errors.append("%s has more than %d items" % (at, schema["maxItems"]))
        if schema.get("uniqueItems") and len(set(map(repr, value))) != len(value):
            errors.append("%s repeats an item" % at)
        if "items" in schema:
            for i, item in enumerate(value):
                errors += schema_errors(item, schema["items"], root, "%s[%d]" % (at, i))
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            errors.append("%s is empty" % at if not value else "%s is too short" % at)
        if len(value) > schema.get("maxLength", len(value)):
            errors.append("%s is %d characters, more than %d" % (at, len(value), schema["maxLength"]))
        if "pattern" in schema and not re.search(schema["pattern"], value):
            errors.append("%s: %r does not match %s" % (at, value, schema["pattern"]))
        if schema.get("format") == "uri" and not URI.match(value):
            errors.append("%s: %r is not an http(s) address" % (at, value))
    return errors


def link_problems(path, text, known):
    """The relative links of a Markdown file that lead nowhere. A link to a loop is ../<id>/card.md from a card,
    <id>/card.md from loops/, ../loops/<id>/card.md from elsewhere; it must name a loop."""
    problems = []
    for link in re.findall(r"\]\(([^)\s#]+)(?:#[^)]*)?\)", FENCE.sub("", text)):
        if re.match(r"^[a-z][a-z0-9+.-]*:", link, re.I):
            continue
        target = (path.parent / link).resolve()
        card = target.parent.name if target.name == "card.md" and target.parent.parent == LOOPS.resolve() else None
        if card and card not in known and not target.exists():
            problems.append("link to no loop: %s" % link)
        elif not card and not target.exists():
            problems.append("broken link %s" % link)
    return problems


def source_talk(path, body):
    """The lines of a card's body, outside code blocks, that talk about the card's source instead of instructing."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    offset = text[:len(text) - len(body)].count("\n") if text.endswith(body) else 0
    problems, fenced = [], False
    for number, line in enumerate(body.splitlines(), start=offset + 1):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        for pattern in [] if fenced else SOURCE_TALK:
            m = pattern.search(line)
            if m:
                problems.append("line %d talks about the card's source (%r): say what to do; where the text came "
                                "from goes in links (FORMAT.md, The voice)" % (number, m.group(0)))
    return problems


def check_loop_card(path, fm, body, root, loop_phases, known):
    """A loop card against the schema, and what a schema cannot say about it."""
    errors = schema_errors(fm, root, root)
    if not isinstance(fm, dict):
        return errors
    if path != TEMPLATE and fm.get("id") != path.parent.name:
        errors.append("id %r is not the folder's name, %s" % (fm.get("id"), path.parent.name))
    prose = FENCE.sub("", body)
    if re.search(r"^# ", prose, re.M):
        errors.append("an H1: the title is in the frontmatter, and the body starts with ## Why")
    errors += source_talk(path, body)
    heads = re.findall(r"^## (.+?)\s*$", prose, re.M)
    errors += ["unknown section ## %s; the sections are %s" % (h, ", ".join(SECTIONS)) for h in heads
               if h not in SECTIONS]
    errors += ["missing ## %s" % s for s in REQUIRED_SECTIONS if s not in heads]
    for name in heads:
        if name in SECTIONS and not re.search(r"^## %s[ \t]*\n\s*(?!## )\S" % re.escape(name), prose, re.M):
            errors.append("## %s is empty" % name)
    known_heads = [h for h in heads if h in SECTIONS]
    if len(set(known_heads)) != len(known_heads):
        errors.append("a section appears twice")
    elif known_heads != sorted(known_heads, key=SECTIONS.index):
        errors.append("the sections are not in the order %s" % " → ".join(SECTIONS))
    if ("agent" in fm) != ("Agent step" in heads):
        errors.append("the agent field and the ## Agent step section go together")
    speed = fm.get("speed")
    if isinstance(speed, list) and len(speed) == 2 and all(s in SPEEDS for s in speed) \
            and SPEEDS.index(speed[0]) > SPEEDS.index(speed[1]):
        errors.append("speed %s: a range is [from, to], the faster first" % speed)
    for token in fm.get("places") or []:
        well_formed = isinstance(token, str) and re.search(root["$defs"]["place"]["pattern"], token)
        problem = well_formed and place_problem(token, loop_phases)
        if problem:
            errors.append("place %r %s" % (token, problem))
    for other in fm.get("related") or []:
        if other == fm.get("id"):
            errors.append("related names the card itself")
        elif path != TEMPLATE and other not in known:
            errors.append("related: no loop %r" % other)
    image = fm.get("image")
    if isinstance(image, str):
        file = path.parent / image
        if not file.is_file():
            errors.append("image %s is not in the card's folder" % image)
        elif file.stat().st_size > IMAGE_MAX_BYTES:
            errors.append("image %s is %d KB, more than %d KB" % (image, file.stat().st_size // 1024,
                                                                 IMAGE_MAX_BYTES // 1024))
    if path != TEMPLATE:
        errors += link_problems(path, body, known)
    return errors


def check():
    errors = []
    root = schema()
    loop_phases = super_loop_phases()
    paths = loop_cards()
    known = {p.parent.name for p in paths}
    places_of, human = {}, set()
    for path in paths + ([TEMPLATE] if TEMPLATE.exists() else []):
        rel = path.relative_to(HARNESS)
        fm, body, problem = read(path)
        if problem or fm is None:
            errors.append("%s: %s" % (rel, problem or "no frontmatter"))
            continue
        errors += ["%s: %s" % (rel, e) for e in check_loop_card(path, fm, body, root, loop_phases, known)]
        if path != TEMPLATE and isinstance(fm, dict):
            places_of[path.parent.name] = [t for t in fm.get("places") or [] if isinstance(t, str)]
            if fm.get("sensor") == "human":
                human.add(path.parent.name)
    stray = sorted(p.name for p in LOOPS.iterdir() if p.is_dir() and not p.name.startswith("_")
                   and not (p / "card.md").exists())
    errors += ["loops/%s/: a folder without card.md" % name for name in stray]
    for path in sorted(LOOPS.glob("*.md")) + sorted(SUPER.glob("*.md")):
        errors += ["%s: %s" % (path.relative_to(HARNESS), e)
                   for e in link_problems(path, path.read_text(encoding="utf-8"), known)]
    errors += check_super_loops()
    errors += check_places(places_of)
    errors += check_human_page(human)
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != build_index():
        errors.append("loops/index.yaml is out of date: run python3 scripts/catalog.py index")
    text = README.read_text(encoding="utf-8") if README.exists() else ""
    updated = readme_with_list(text)
    if updated is None:
        errors.append("loops/README.md has no list of loops between %s and %s" % (LIST_BEGIN, LIST_END))
    elif updated != text:
        errors.append("the list of loops in loops/README.md is out of date: run python3 scripts/catalog.py index")
    return errors


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "index":
        INDEX.write_text(build_index(), encoding="utf-8")
        text = README.read_text(encoding="utf-8")
        updated = readme_with_list(text)
        if updated is None:
            sys.exit("loops/README.md has no list of loops between %s and %s" % (LIST_BEGIN, LIST_END))
        README.write_text(updated, encoding="utf-8")
        print("wrote %s and the list in %s (%d loops)" % (INDEX, README, len(loop_cards())))
    elif cmd == "check":
        errors = check()
        print("\n".join(errors) if errors else "OK: %d loops" % len(loop_cards()))
        sys.exit(1 if errors else 0)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
